const DICTS: Record<Lang, Record<Key, string>> = { uz, ru, en };
export type MessageKey = Key;

export function translate(k: Key, vars?: Record<string, string | number>, lang: Lang = current) {
  let s = DICTS[lang][k] ?? uz[k] ?? k;
  if (vars) for (const [n, v] of Object.entries(vars)) s = s.replaceAll(`{${n}}`, String(v));
  return s;
}

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string };
const I18n = createContext<Ctx | null>(null);

/** Asosiy til — o'zbekcha. Telefon ruscha bo'lsa ruscha; ingliz tili faqat profilda tanlansa
 * (aks holda inglizcha telefonli foydalanuvchi profili ham "en" bo'lib, AI va xabarlar inglizcha kelardi). */
function deviceLang(): Lang {
  return getLocales()[0]?.languageCode === "ru" ? "ru" : "uz";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("uz");
  useEffect(() => {
    prefs.get("dailer.lang").then((v) => {
      const l = v === "uz" || v === "ru" || v === "en" ? v : deviceLang();
      current = l;
      setLangState(l);
    });
  }, []);
  const setLang = useCallback((l: Lang) => {
    current = l;
    setLangState(l);
    prefs.set("dailer.lang", l);
  }, []);
  const t = useCallback((k: Key, vars?: Record<string, string | number>) => translate(k, vars, lang), [lang]);
  return <I18n.Provider value={{ lang, setLang, t }}>{children}</I18n.Provider>;
}

export function useI18n() {
  const c = useContext(I18n);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}
